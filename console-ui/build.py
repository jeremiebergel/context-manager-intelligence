"""Build the CMI Console shells. Dependency-free on purpose: no npm, no bundler, auditable.

    python console-ui/build.py           # writes cmi_console/desktop/plugin.js
    python console-ui/build.py --check   # exit 1 if the committed bundle is stale

The Hermes disk-plugin loader accepts a single ESM file importing only the SDK and React, so
the host-neutral core is inlined into the shell at the /*@@CORE@@*/ marker.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
REPO = ROOT.parent
OUT = REPO / "cmi_console" / "desktop" / "plugin.js"
HEADER = "// GENERATED by console-ui/build.py from console-ui/src — do not edit by hand.\n"


def build() -> str:
    core = (ROOT / "src" / "core.js").read_text(encoding="utf-8")
    shell = (ROOT / "src" / "shell-hermes.js").read_text(encoding="utf-8")
    if "/*@@CORE@@*/" not in shell:
        raise SystemExit("shell-hermes.js lost its /*@@CORE@@*/ marker")
    core = core.replace("export function createConsole", "function createConsole", 1)
    if "\nimport " in "\n" + core or "export " in core:
        raise SystemExit("core.js must not import or export anything besides createConsole")
    return HEADER + shell.replace("/*@@CORE@@*/", core.strip() + "\n", 1)


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"stale: {OUT.relative_to(REPO)} (run python console-ui/build.py)")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} ({len(text):,} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
